"""Check SANDBOX names and maintain tiny Claude entrypoints to canonical skills."""
from __future__ import annotations

import argparse
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parents[2]
MARKER = "<!-- Generated by tools/repository/sync_skills.py; canonical instructions in .agents. -->"


def expected(path):
    content = path.read_text(encoding="utf-8")
    match = re.match(r"---\s*\nname: ([a-z0-9-]+)\ndescription: ([^\n]+)\n---", content)
    if not match or match[1] != path.parent.name or not match[1].startswith("sandbox-"):
        raise ValueError("Nom/frontmatter SANDBOX invalide : "+str(path))
    name, description = match.groups()
    return f"---\nname: {name}\ndescription: {description}\n---\n\n{MARKER}\n\nLis et applique le skill canonique [{name}](../../../.agents/skills/{name}/SKILL.md) avant toute action. Travaille depuis la racine du dépôt. Les arguments de la commande précisent le mode ou le rang demandé ; toute la logique métier reste dans le moteur Python commun.\n"


def sync(root=ROOT, *, write=False):
    paths = sorted((root / ".agents/skills").glob("*/SKILL.md"))
    if not paths:
        raise ValueError("Aucun skill canonique.")
    errors = []
    names = {p.parent.name for p in paths}
    for path in paths:
        body = expected(path)
        target = root / ".claude/skills" / path.parent.name / "SKILL.md"
        if not target.exists() or target.read_text(encoding="utf-8") != body:
            if write:
                if target.exists() and MARKER not in target.read_text(encoding="utf-8"):
                    raise ValueError("Point d'entrée Claude non géré : "+str(target))
                target.parent.mkdir(parents=True, exist_ok=True)
                target.write_text(body, encoding="utf-8")
            else:
                errors.append(str(target))
    for path in (root / ".claude/skills").glob("*/SKILL.md"):
        if path.parent.name not in names:
            errors.append("Point d'entrée sans skill canonique : "+str(path))
    if errors:
        raise ValueError("Entrées de skills à synchroniser :\n"+"\n".join(errors))
    return len(paths)


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--write", action="store_true")
    args = parser.parse_args()
    print(f"{sync(write=args.write)} skills sandbox- vérifiés.")
